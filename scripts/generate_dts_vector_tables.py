#!/usr/bin/env python3
"""Generate DirnexCore's two DTS vector-quantization code books from FFmpeg's copy of them.

Usage:
    curl -fsSLO https://raw.githubusercontent.com/FFmpeg/FFmpeg/n8.0/libavcodec/dcadata.c
    python3 -I scripts/generate_dts_vector_tables.py dcadata.c n8.0

ETSI TS 102 114 calls Annex D normative, and D.10's two code books with it, but no edition prints
them ("Due to its extensive size, this table is not included here"), and every DTS film tried needs
them: about 97 % of a film's frames use ADPCM prediction and the rest high-frequency VQ. FFmpeg's
`libavcodec/dcadata.c` reproduces them, and only these two tables are taken from it; everything else
comes from the specification (scripts/generate_dts_tables.py). Where they come from is in NOTICE.

The tables are written as base64, little-endian, in two files under SwiftLint's file_length: 16 384
`Int16` prediction coefficients (× 2^13) and 32 768 `Int8` high-frequency samples (× 2^4).
`DTSVectorTables.standard` decodes them once, on first use.
"""

import base64
import hashlib
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERVICES = os.path.join(ROOT, 'DirnexCore/Sources/DirnexCore/Services')
WIDTH = 96


def table(source, name):
    match = re.search(re.escape(name) + r'\)?(\[[^\]]*\])+\s*=\s*\{', source)
    if not match:
        sys.exit(f'{name} is not in the file')
    start = end = match.end()
    depth = 1
    while depth:
        depth += {'{': 1, '}': -1}.get(source[end], 0)
        end += 1
    body = re.sub(r'/\*.*?\*/', '', source[start:end - 1], flags=re.S)
    return [int(value) for value in re.findall(r'-?\d+', body)]


def write(file_name, header, doc, property_name, data):
    encoded = base64.b64encode(data).decode('ascii')
    lines = [encoded[i:i + WIDTH] for i in range(0, len(encoded), WIDTH)]
    text = header + '\n'
    text += 'extension DTSVectorTables {\n'
    text += f'    /// {doc}\n'
    text += f'    static let {property_name} = """\n'
    text += '\n'.join('    ' + line for line in lines) + '\n'
    text += '    """\n'
    text += '}\n'
    with open(os.path.join(SERVICES, file_name), 'w') as out:
        out.write(text)


def main():
    path, version = sys.argv[1], sys.argv[2]
    raw = open(path, 'rb').read()
    digest = hashlib.sha256(raw).hexdigest()
    source = raw.decode('utf-8')

    prediction = table(source, 'ff_dca_adpcm_vb')
    high = table(source, 'ff_dca_high_freq_vq')
    if len(prediction) != 4096 * 4 or len(high) != 1024 * 32:
        sys.exit(f'{len(prediction)} prediction coefficients and {len(high)} samples')
    # The one entry the specification prints: "the first entry in the table gives 9928" (D.10.1).
    if prediction[0] != 9928:
        sys.exit(f'the first prediction coefficient is {prediction[0]}, where D.10.1 says 9928')
    if not all(-32768 <= v < 32768 for v in prediction) or not all(-128 <= v < 128 for v in high):
        sys.exit('a value out of range')

    header = (
        f'// Generated by scripts/generate_dts_vector_tables.py from FFmpeg {version}\'s\n'
        f'// libavcodec/dcadata.c, sha256 {digest}.\n'
        '// Do not edit by hand: run the script again. Where the numbers come from is in NOTICE.\n'
    )
    write(
        'DTSVectorTablesPrediction.swift', header,
        'ETSI TS 102 114 D.10.1: 4 096 vectors of four ADPCM coefficients × 2^13, as little-endian `Int16`.',
        'predictionData', struct.pack(f'<{len(prediction)}h', *prediction),
    )
    write(
        'DTSVectorTablesHighFrequency.swift', header,
        'ETSI TS 102 114 D.10.2: 1 024 vectors of 32 subband samples × 2^4, as `Int8`.',
        'highFrequencyData', struct.pack(f'<{len(high)}b', *high),
    )
    print(f'{len(prediction)} prediction coefficients, {len(high)} high-frequency samples')


if __name__ == '__main__':
    main()
