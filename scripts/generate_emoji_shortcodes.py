#!/usr/bin/env python3
"""Generate DirnexCore's emoji shortcode table from GitHub's gemoji (PLAN.md §M39 ▸ Slice 6).

Usage:
    curl -fsSLO https://raw.githubusercontent.com/github/gemoji/v4.1.0/db/emoji.json
    python3 -I scripts/generate_emoji_shortcodes.py emoji.json v4.1.0

The table is gemoji's `db/emoji.json` reduced to its aliases: every name GitHub turns into an emoji,
paired with the emoji it becomes. It is written as one string literal rather than a dictionary
literal, because a 1 900-entry dictionary literal is slow for the Swift compiler to type-check, and
the core ships no resources. `MarkdownEmoji.table` reads it once, on first use.

gemoji is MIT-licensed (Copyright (c) 2019 GitHub, Inc.), and its notice is in NOTICE.
"""

import hashlib
import json
import re
import sys

OUTPUT = 'DirnexCore/Sources/DirnexCore/Services/MarkdownEmojiTable.swift'
# Each line of the literal stays under SwiftLint's line_length, counted in code points, which is
# never fewer than Swift's grapheme count.
WIDTH = 96
INDENT = '    '


def main() -> None:
    source_path, version = sys.argv[1], sys.argv[2]
    raw = open(source_path, 'rb').read()
    digest = hashlib.sha256(raw).hexdigest()
    entries = json.loads(raw)

    pairs = []
    seen = set()
    for entry in entries:
        emoji = entry.get('emoji')
        if not emoji:
            # A custom GitHub image (`:octocat:`) has no character, and stays its own text.
            continue
        if any(character.isspace() for character in emoji):
            sys.exit(f'emoji for {entry["aliases"]} holds whitespace, which the table splits on')
        for alias in entry['aliases']:
            if not re.fullmatch(r'[a-z0-9_+-]+', alias):
                sys.exit(f'alias {alias!r} is outside the shortcode alphabet MarkdownEmoji scans')
            if alias in seen:
                sys.exit(f'alias {alias!r} appears twice')
            seen.add(alias)
            pairs.append(f'{alias} {emoji}')

    lines = []
    current = ''
    for pair in pairs:
        candidate = f'{current} {pair}' if current else pair
        if len(INDENT) + len(candidate) > WIDTH and current:
            lines.append(current)
            current = pair
        else:
            current = candidate
    if current:
        lines.append(current)

    # One indent, as SwiftFormat's `indent` rule has a multi-line literal at its declaration's scope.
    body = '\n'.join(INDENT + line for line in lines)
    swift = f'''// Generated by scripts/generate_emoji_shortcodes.py from gemoji {version}'s db/emoji.json,
// sha256 {digest}.
// Do not edit by hand: run the script again.
//
// gemoji is Copyright (c) 2019 GitHub, Inc., MIT License; the notice is in NOTICE.

extension MarkdownEmoji {{
    /// How many shortcodes `tableSource` holds, so a test can tell a table that parsed whole from
    /// one where an emoji ran into its neighbour.
    static let tableCount = {len(pairs)}

    /// Every shortcode GitHub draws as an emoji, as `name emoji` pairs separated by whitespace.
    static let tableSource = """
{body}
    """
}}
'''
    with open(OUTPUT, 'w', encoding='utf-8') as handle:
        handle.write(swift)
    print(f'{len(pairs)} shortcodes in {len(lines)} lines -> {OUTPUT}')


if __name__ == '__main__':
    main()
